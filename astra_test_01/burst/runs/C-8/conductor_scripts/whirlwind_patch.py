#!/usr/bin/env python3
"""Post-export patch: binds the Eye-of-Reckoning WHIRLWIND VFX to the 2D pixel
"EoR Warlord" keeper in an already-exported Godot project.

MUST RUN AFTER attack_patch.py. This patch anchors on the exact blocks that
attack_patch.py inserts into scripts/keeper.gd, so "run attack_patch.py first"
is enforced mechanically rather than asked for in a comment.

Usage:
    python3 whirlwind_patch.py <path to exported godot dir>
    e.g. python3 whirlwind_patch.py runs/C-8/cliffside_v40-warlord3/godot

---------------------------------------------------------------------------
THE RIBBON RUNS ON A LEVEL BAND, NOT ON THE DRAWN MACE. Conductor correction,
Run C-8, after Matt spotted the mace height wandering.

The source's rule is "generated from the WEAPON'S ACTUAL POSITION", and the
first build of this patch took that literally: it read the per-frame mace-head
pixels out of vfx_fit.json and drove both the ribbon's bearing and its radius
from them. Measured, that is not a sweep. Across the eight attack stills the
mace head sits at

    0.180  0.184  0.238  0.594  0.674  0.891  0.912  0.962

of figure height above the sole -- a spread of 0.782 H against the reference
clip's own sweep band of [0.551, 0.746], spread 0.195. Four times the
reference's wander, and on three frames the head is level with or above the
helm. A ribbon threaded through those points is a scribble, not an ellipse.

So the HEIGHT comes from a constant band (SWEEP_BAND +/- SWEEP_WOBBLE, the 2D
form of the source's SWEEP_Y / SWEEP_WOBBLE plane), the ANGLE comes from the
animation frame by the cells' own declared construction (still k = 45 deg from
S), and the RADII stay as the conductor measured them. Where the ribbon and the
drawn mace disagree, the ribbon is right; the art is being regenerated onto
this band.

NOTHING BELOW READS A MACE ROW to drive anything. The only use left for
vfx_fit.json's per-frame mace data is `report_level_band_evidence`, which
prints the height spread that justified the band and is never consumed.
---------------------------------------------------------------------------

What it does:
  1. Validates the project is attack-patched (attack_* animations in
     frames/keeper.tres at exactly 0.400 s/loop, the attack input action, the
     attack_patch marker in keeper.gd).
  2. Reads runs/C-8/vfx_fit.json for the sprite registration it still trusts:
     canvas, figure height, sole row, body-centre X, R_TRAIL and R_ENGAGE.
  3. Derives, per direction, the PHASE ROLL of that direction's 8 frames
     against the canonical attack_S still order, BY HASH. (The C-8 cells are
     TURNAROUND-AS-SPIN: all eight facings are exact rotations of ONE eight-
     still revolution -- registration.json method R-C8-5/R-C8-4. This script
     re-derives the rotation from the bytes rather than trusting that note,
     and fails loudly if any direction is not a clean rotation.)
  4. Checks the level band against the 2D restatement of the source's
     disjoint-band inequality and fails loudly if it is violated.
  5. Writes <project>/whirlwind_fit.json (generated; regenerated byte-identical
     on every run) and <project>/scripts/whirlwind.gd (generated verbatim).
  6. Patches <project>/scripts/keeper.gd, marker-guarded, to build the effect
     in _ready() and to drive begin()/end() off the attack state transitions.

No .tscn is edited. The two draw layers are created in GDScript with explicit
z_index, which is also how the near/far split is enforced -- see whirlwind.gd.

Idempotent: whirlwind_fit.json and scripts/whirlwind.gd are regenerated from
scratch each run (byte-identical); the keeper.gd patch is marker-guarded.

Fails loudly: every validation runs before anything is written; any
inconsistency raises and exits non-zero with no partial write.
"""
import hashlib
import json
import math
import re
import sys
from pathlib import Path

DIRECTIONS = ('S', 'SW', 'W', 'NW', 'N', 'NE', 'E', 'SE')
SCRIPT_DIR = Path(__file__).resolve().parent
RUN_ROOT = SCRIPT_DIR.parent              # runs/C-8
CELLS_ROOT = RUN_ROOT / 'cells'
VFX_FIT = RUN_ROOT / 'vfx_fit.json'

# ===========================================================================
# THE CONSTANTS BLOCK. Everything the new character frames could move lives
# here, so they drop in without a code change.
# ===========================================================================

# ---------------------------------------------------------------------------
# THE SWEEP BAND. The 2D form of the source's SWEEP_Y = 1.20 m on H_STAND =
# 1.85 m (0.6486 of standing height) with SWEEP_WOBBLE = 0.08 m (+/- 0.0432 H).
# Set to 0.55 H on this chibi, where the proportions differ from the 3D rig's.
# ---------------------------------------------------------------------------
SWEEP_BAND = 0.55         # sweep-plane height above the sole, of figure height
SWEEP_WOBBLE = 0.04       # helical wobble amplitude, of figure height

# ---------------------------------------------------------------------------
# ⚑ THE DISJOINT-BAND INEQUALITY, RESTATED FOR 2D AND ASSERTED BELOW.
#
# The source turned "renders over the caster's lower body" into a number:
# trail band [1.02, 1.38] m against LOWER_BODY_TOP (hips) 0.9088 m -- disjoint
# by 0.111 m. The same discipline here, in figure-height units on this chibi:
# the sweep plane must sit ABOVE the hips and BELOW the chin. These two are the
# guard, and they are checked rather than admired.
# ---------------------------------------------------------------------------
LOWER_BODY_TOP = 0.35     # hips
HEAD_BOTTOM = 0.753       # chin / neck pinch

# ---------------------------------------------------------------------------
# ⚑ THE PHASE ANCHOR IS DECLARED, NOT FITTED, AND THAT IS A DELIBERATE CALL.
#
# The cells' own registration.json declares the construction: "phase assignment
# is BY CONSTRUCTION (index k = 45 deg from S), not independently verified",
# with the flag "angle spacing is eye-judged, not measured". Canonical still 0
# is the S-facing still, and S faces the camera -- screen-down -- which in this
# file's bearing convention (x right, y down) is +90 deg.
#
# I did try to fit this to the current art instead, using the mace X ONLY (the
# rows being the corrupted channel): the one-parameter least squares returns
# 184.2 deg with a residual RMS of 32 % of R_TRAIL. A 32 % residual on a
# one-parameter fit is not a phase measurement, it is a statement that these
# eight stills do not lie on a uniform sweep in X either. So the fit is
# REPORTED and NOT USED, and the declared construction stands.
#
# This is the one constant to move if the art wants the ribbon registered
# elsewhere. It is independent of the SIGN of the sweep, which is the separate
# (and separately evidenced) constant immediately below.
# ---------------------------------------------------------------------------
SWEEP_BEARING0_DEG = 90.0   # bearing of the sweep at canonical frame 0

# ---------------------------------------------------------------------------
# ⚑ THE SIGN OF THE SWEEP. GET THIS BACKWARDS AND THE RIBBON COUNTER-ROTATES
#   AGAINST THE CHARACTER, WHICH IS EXACTLY WHAT SHIPPED AND WHAT MATT CAUGHT.
#
# THE CONVENTION, STATED ONCE SO IT CANNOT BE RE-DERIVED WRONG. Bearings are
# screen-space with X RIGHT and Y DOWN, and a point on the sweep sits at
#
#       ( cos(theta) * R ,  sin(theta) * R * GROUND_SQUASH )
#
# Because Y is DOWN, sin(theta) > 0 is the BOTTOM of the screen -- the side
# NEAREST the camera. So walking theta upward goes
#
#       0 deg  RIGHT  ->  90 deg  BOTTOM  ->  180 deg  LEFT  ->  270 deg  TOP
#
# i.e. right -> down -> left -> up, which is CLOCKWISE to the viewer.
#
#       theta INCREASING  ==  CLOCKWISE on screen  ==  +360 per revolution
#       theta DECREASING  ==  ANTICLOCKWISE        ==  -360 per revolution
#
# ⚑ THIS VALUE HAS BEEN BOTH SIGNS, AND THE SECOND CHANGE WAS NOT A CORRECTION
#   OF THE FIRST. READ THIS BEFORE "FIXING" IT BACK.
#
# It shipped at -360, was changed to +360 on 2026-09-21 to match the warlord4
# art, and is -360 again on warlord5. Nothing about the convention above
# changed and no measurement was wrong: THE ART WAS DELIBERATELY REVERSED
# BETWEEN THE TWO BUILDS, and this constant simply follows it.
#
# MATT'S RULING, 2026-09-21, which is the reason and will outlive the builds:
# a RIGHT-HANDER turns COUNTER-CLOCKWISE. The forehand sweep starts on the
# right and crosses to the left, and the body keeps turning left; right-handed
# hammer and discus throwers rotate counter-clockwise seen from above. The
# warlord4 art turned clockwise, which is effectively a repeated BACKHAND.
#
# ⚑ AND THE FIX WAS FRAME REVERSAL, NOT MIRRORING, WHICH IS THE WHOLE POINT.
#   Reversing the 16-frame revolution flips the rotational sense and PRESERVES
#   handedness. Mirroring would have done the opposite -- fixed the sense and
#   swapped the hands -- which is a separate defect Matt is holding a decision
#   on. Two transforms, both of which "fix the spin", and only one of which is
#   correct: worth knowing which was used before reasoning about this file.
#
# VERIFIED ON warlord5's OWN BYTES rather than inferred from the note:
#   * The 16 frames are warlord4's frames at indices [0, 15, 14, ... 1] --
#     every step -1 mod 16, i.e. an exact reversal anchored at frame 0, with
#     the identical image set (hash-for-hash).
#   * SHIELD TEST, the same instrument run on warlord4 and independent of the
#     mace: the shield is widest when FACE-ON, and face-on to the camera is its
#     NEAREST point, theta = +90. Its horizontal centroid through that frame
#     runs +17 px -> +68 -> +115 off the body axis: moving RIGHT, at +98 px
#     across the pair -- the exact mirror of warlord4's -98. The tangent at
#     theta = 90 for DECREASING theta is (+1, 0) = RIGHT.
#     THETA DECREASING => COUNTER-CLOCKWISE => this constant is NEGATIVE.
#   * Per-direction roll, derived from the bytes: S=0 SW=14 W=12 NW=10 N=8
#     NE=6 E=4 SE=2, i.e. (-2k) mod 16 -- inverted from warlord4's +2k exactly
#     as a reversal requires.
#
# ⚑ A NOTE ON WHAT `sense_check()` CAN AND CANNOT TELL YOU. It compares the
#   drawn geometry against this constant, and both derive from this constant,
#   so it CANNOT detect a disagreement with the CHARACTER -- it will pass at
#   either sign. It catches a geometry/constant desync, nothing more. The only
#   thing that ties this file to the art is a measurement of the ART, like the
#   shield test above. Re-run that, not just the probe, whenever the art moves.
#
# ⚑ AN INSTRUMENT I BUILT AND THEN REJECTED, recorded so nobody rebuilds it:
#   tracking the mace head by its cool teal glint returned the opposite answer
#   on warlord4 with cross-product votes at 5 against 6, i.e. a coin flip. It
#   was catching the shield's green rim-light as often as the mace, and on one
#   frame placed the mace at the BOTTOM of the sweep when it is plainly
#   upper-left. A tracker that is wrong half the time averages to noise and
#   then reports the noise as a direction. The check ran; the check was not
#   the check.
# ---------------------------------------------------------------------------
SWEEP_REVOLUTION_DEG = -360.0

# ---------------------------------------------------------------------------
# GROUND_SQUASH -- the vertical foreshortening of a circle lying on the
# cliffside's ground plane. CARRIED from this project's own ground-plane
# primitives: every ground-lying VFX surface the exporter emits is drawn as
# `scale = Vector2(1, ground_squash)` on a circular texture (the G2 field disc,
# the G4 "orbit ellipse", the floor light, the impact decal). Across the 28
# instances shipped in a cliffside export the modal value is 0.60 (0.58 in the
# e3 family, 0.72 in one), and export/effect_kit.py validates the field into
# [0.50, 0.65]. The sweep circle is the same geometric object as G4's orbit
# ellipse, so it must sit on the same floor as the rest of the scene's effects.
#
# NOT the contact shadow's 0.08/0.22 = 0.364: those are two INDEPENDENT art
# constants in export/parallax_scene.py (footprint width 0.22*H, blob height
# 0.08*H), a deliberately flattened contact blob, not a projection.
#
# NOT measurable from the mace locus: a free 4-parameter ellipse fit to the 8
# measured mace heads returns 0.92, but the 8 samples leave 97 deg and 112 deg
# gaps that straddle BOTH minor-axis extremes -- the data cannot see the minor
# axis at all. Pinning the squash at 0.60 and refitting returns a semi-major
# axis of 185.79 px against the conductor's measured R_TRAIL of 186.97 px
# (0.6 % agreement), which is the corroboration this constant rests on.
# ---------------------------------------------------------------------------
GROUND_SQUASH = 0.60

# CARRIED from wwcr_whirlwind.gd: R_ENGAGE / R_TRAIL = 3.5150 / 2.3598.
ENGAGE_RATIO = 1.4895

LOOP_SECONDS = 0.40


def fail(msg):
    print('whirlwind_patch: FAIL: ' + msg, file=sys.stderr)
    sys.exit(1)


# ---------------------------------------------------------------------------
# Step 1: the project must already be attack-patched
# ---------------------------------------------------------------------------

ANIMATION_BLOCK_RE = re.compile(
    r'\{"frames": \[(?P<frames>.*?)\], "loop": (?P<loop>true|false), '
    r'"name": &"(?P<name>[^"]+)", "speed": (?P<speed>[0-9.]+)\}', re.DOTALL)
FRAME_ID_RE = re.compile(r'ExtResource\("(\d+)"\)')
ATTACK_MARKER = '    # PATCH(drax attack_patch): attack state'


def require_attack_patched(project):
    tres = project / 'frames' / 'keeper.tres'
    if not tres.is_file():
        fail(f'expected SpriteFrames resource not found: {tres}')
    text = tres.read_text()
    found = {}
    for m in ANIMATION_BLOCK_RE.finditer(text):
        found[m.group('name')] = (len(FRAME_ID_RE.findall(m.group('frames'))),
                                  float(m.group('speed')), m.group('loop') == 'true')
    missing = [d for d in DIRECTIONS if f'attack_{d}' not in found]
    if missing:
        fail(f'frames/keeper.tres has no attack_{{{",".join(missing)}}} animations -- '
             f'run attack_patch.py against this project first')
    counts = {}
    for d in DIRECTIONS:
        n, fps, loop = found[f'attack_{d}']
        if not loop:
            fail(f'attack_{d} is not a looping animation -- refusing to phase-lock a '
                 f'ribbon to a one-shot')
        if abs(n / fps - LOOP_SECONDS) > 1e-6:
            fail(f'attack_{d}: n/speed = {n}/{fps} = {n / fps:.6f}s, expected exactly '
                 f'{LOOP_SECONDS}s -- the ribbon revolution is defined as one animation '
                 f'loop and cannot be phase-locked to a loop of another length')
        # ⚑ FRAME COUNT IS NOT CONSTRAINED, AND MUST NOT BE. The ribbon locks to
        # the loop's PHASE, not to a frame index: builds differ (the turnaround
        # is 8 @ 20 fps; the clip cut is 12 @ 30 and 9 @ 22.5 for N/NE/NW) and
        # they can even differ BETWEEN DIRECTIONS in the same build. All that
        # matters is the 0.400 s above, which is what makes the same effect drop
        # onto either build unchanged.
        counts[d] = n

    pg = project / 'project.godot'
    if not pg.is_file() or not re.search(r'^attack=', pg.read_text(), re.MULTILINE):
        fail('project.godot has no "attack=" input action -- run attack_patch.py first')

    keeper = project / 'scripts' / 'keeper.gd'
    if not keeper.is_file():
        fail(f'keeper.gd not found: {keeper}')
    if ATTACK_MARKER not in keeper.read_text():
        fail('scripts/keeper.gd does not carry the attack_patch marker -- run '
             'attack_patch.py against this project first')
    return counts


