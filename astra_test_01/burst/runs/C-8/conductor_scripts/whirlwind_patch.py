	_near_dust = _mk_layer("WhirlwindNearDust", 1, false, true, true)
	_near_arc = _mk_layer("WhirlwindNearArc", 1, true, true, false)

	set_element(Color.from_hsv(ELEMENT_HUE_DEG / 360.0, 0.55, 1.0))
