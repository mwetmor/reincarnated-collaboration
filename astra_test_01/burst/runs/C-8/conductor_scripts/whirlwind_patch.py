def patch_keeper_gd(project):
    path = project / 'scripts' / 'keeper.gd'
    text = path.read_text()
    if MARKER in text:
        return False

    for name, anchor in (('_ready animation hookup', READY_ANCHOR),
                         ('fallback_remaining declaration', VAR_ANCHOR),
                         ('attack hold block', ATTACK_HOLD_ANCHOR),
                         ('attack trigger block', ATTACK_TRIGGER_ANCHOR)):
        if text.count(anchor) != 1:
            fail(f'keeper.gd: expected exactly one occurrence of the {name} '
                 f'(found {text.count(anchor)}) -- unrecognized controller shape, '
                 f'refusing to guess where to bind the whirlwind')

    text = text.replace(VAR_ANCHOR, VAR_ANCHOR + VAR_BLOCK, 1)
    text = text.replace(READY_ANCHOR, READY_ANCHOR + READY_BLOCK, 1)
    text = text.replace(ATTACK_HOLD_ANCHOR, ATTACK_HOLD_PATCHED, 1)
    text = text.replace(ATTACK_TRIGGER_ANCHOR, ATTACK_TRIGGER_PATCHED, 1)
    path.write_text(text)
    return True


