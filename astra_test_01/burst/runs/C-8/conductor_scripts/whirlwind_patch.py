def write_fit_resource(project, fit, rolls, band, counts, mode):
    lo, hi, mlo, mhi, mlo_px, mhi_px = band
    doc = {
        '_generated_by': 'runs/C-8/conductor_scripts/whirlwind_patch.py',
        '_source': 'runs/C-8/vfx_fit.json (registration + radii only)',
        '_note': ('LEVEL-BAND sweep. The ribbon runs on a constant plane at '
                  'sweep_band (of figure height, above the sole) with a helical '
                  'wobble of sweep_wobble, NOT on the drawn mace head -- whose '
                  'height wanders 4x the reference band. Bearing is the cells\' '
                  'declared construction: phase `rev` sits at bearing0 + '
                  'revolution_deg * rev, screen convention x right / y down.'),
        'canvas': fit['canvas'],
        'figure_height_px': fit['figure_height'],
        'sole_row': fit['sole_row'],
        'body_centre_x': fit['body_centre'][0],
        'r_trail_px': fit['R_TRAIL_px'],
        'r_engage_px': fit['R_ENGAGE_px'],
        'ground_squash': GROUND_SQUASH,
        'loop_seconds': LOOP_SECONDS,
        'sweep_band': SWEEP_BAND,
        'sweep_wobble': SWEEP_WOBBLE,
        'bearing0_deg': SWEEP_BEARING0_DEG,
        'revolution_deg': SWEEP_REVOLUTION_DEG,
        'art_mode': mode,
        'guard': {
            'lower_body_top': LOWER_BODY_TOP,
            'head_bottom': HEAD_BOTTOM,
            'band_lo': round(lo, 6), 'band_hi': round(hi, 6),
            'margin_below_H': round(mlo, 6), 'margin_above_H': round(mhi, 6),
            'margin_below_px': round(mlo_px, 3), 'margin_above_px': round(mhi_px, 3),
        },
        # Per-direction frame count and phase offset AS A FRACTION OF A
        # REVOLUTION -- never a frame index, so a build whose directions have
        # different frame counts (12 and 9 in the clip cut) works unchanged.
        'frames': {d: counts[d] for d in DIRECTIONS},
        'roll_rev': {d: round(rolls[d], 9) for d in DIRECTIONS},
    }
    (project / 'whirlwind_fit.json').write_text(json.dumps(doc, indent=1) + '\n')
    return doc


